export const TOPIC_OF = Object.freeze(
  Object.fromEntries([
    ...Object.entries(TOPIC_IDS).flatMap(([topic, ids]) => ids.map((id) => [id, topic])),
    ...Object.entries(TOPIC_ROWS).flatMap(([topic, rows]) => rows.map(([english]) => [`tp-${slugify(english)}`, topic])),
  ]),
);

export const topicOf = (vocabId) => TOPIC_OF[vocabId] ?? null;
export const isTopic = (id) => TOPICS.some((t) => t.id === id);
// The topics of one course (a topic without `courses` belongs to both).
export const topicsFor = (courseId) => TOPICS.filter((t) => !t.courses || t.courses.includes(courseId));
