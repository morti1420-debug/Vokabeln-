export const grammarById = (id) => GRAMMAR.find((g) => g.id === id) ?? null;

// Every English sentence of the grammar pages that can be played: the examples and the exercises with the right
// answer filled in. The ids name the recordings (audio/de-en/<id>-english.mp3).
export function grammarAudioTexts() {
  return GRAMMAR.flatMap((g) => [
    ...g.examples.map(([en], i) => ({ id: `gr-${g.id}-e${i}`, text: en })),
    ...g.exercises.map(([q, options, answer], i) => ({ id: `gr-${g.id}-x${i}`, text: grammarSpoken(q, options[answer]) })),
  ]);
}

// The English sentence of an exercise with the answer filled in; for reported speech only the reported sentence
// („I am tired.“ → She said she was tired. → "She said she was tired.").
export const grammarSpoken = (q, answer) => q.replace('___', answer).replace(/^.*→\s*/, '');
