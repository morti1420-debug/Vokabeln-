const UMLAUTS = { ä: 'ae', ö: 'oe', ü: 'ue', ß: 'ss' };
function slug(text) {
  return text
    .toLowerCase()
    .replace(/[äöüß]/g, (c) => UMLAUTS[c])
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function build(rows, category, prefix) {
  return rows.map(([german, chinese, exampleDe, exampleZh, cefr, partOfSpeech, acceptedChinese = [], acceptedGerman = []], index) => ({
    id: `${prefix}-${slug(german)}`,
    course: 'zh-de',
    english: german,
    german: chinese,
    exampleEn: exampleDe,
    exampleDe: exampleZh,
    category,
    cefr,
    partOfSpeech,
    acceptedGerman: acceptedChinese,
    acceptedEnglish: acceptedGerman,
    frequencyRank: index + 1,
  })).map((v) => (NOTES_ZH[v.id] ? { ...v, note: NOTES_ZH[v.id] } : v));
}

