// Chinese falls back to English (never to German) for keys that are not translated.
export const DICTIONARIES = { de, en, zh: { ...en, ...zh } };

export function createTranslator(lang = 'de') {
  const dict = DICTIONARIES[lang] ?? de;
  return (key, vars = {}) => {
    const text = dict[key] ?? en[key] ?? de[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
  };
}
